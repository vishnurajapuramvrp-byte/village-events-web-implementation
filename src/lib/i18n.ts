const exactTranslations = new Map(
  Object.entries(telugu).map(([english, translated]) => [english.toLowerCase(), translated]),
);

export function translate(text: string, locale: Locale): string {
  if (locale === "en") return text;
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const content = text.slice(leading.length, text.length - trailing.length);
  if (!content) return text;
  const normalized = content.replace(/\s+/g, " ");
  return `${leading}${exactTranslations.get(normalized.toLowerCase()) ?? content}${trailing}`;
}
